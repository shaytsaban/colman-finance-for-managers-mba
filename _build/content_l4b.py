def _yr(cols, sol, fmt, label='ריבית שנתית אפקטיבית', per=12):
    """Row 7 of a RATE sheet: the rate per period turned into an annual effective rate, written as a conversion."""
    cols['A7'] = label
    sol['C7'] = f'=(1+C2)^{per}-1'
    fmt['C7'] = 'pct4'


