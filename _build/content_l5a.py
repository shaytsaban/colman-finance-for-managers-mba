def pvs(stages, corner='', given_last=True):
    """Stages of a present value, from the end to the start: stage 1 (the latest years) in column C, the next one in D, and so on.
    Each stage: h, rate, nper, and fv as a number (stage 1) or add (a sum received at the stage's end, on top of the value carried back).
    The fv of stage k is the pv of stage k-1 with the sign flipped, plus add. Returns data, sol, fmt and the pv cells."""
    d, s, f, out = {'A1': corner or 'הנתון', 'B1': 'שם'}, {}, {}, []
    for k, (he, en) in enumerate(FVROWS):
        d[f'A{2 + k}'] = he; d[f'B{2 + k}'] = en
    for j, c in enumerate(stages):
        L = chr(67 + j); P = chr(66 + j)
        d[f'{L}1'] = c['h']; d[f'{L}2'] = c['rate']; d[f'{L}3'] = c['nper']; d[f'{L}4'] = 0
        s[f'{L}5'] = f'=PV({L}2,{L}3,{L}4,{L}6)'
        if j == 0:
            d[f'{L}6'] = c['fv']
        else:
            s[f'{L}6'] = f'=-{P}5' + (f"+{c['add']}" if c.get('add') else '')
        f[f'{L}2'] = _pctf(c['rate']); f[f'{L}4'] = 'num0'; f[f'{L}5'] = 'num2'; f[f'{L}6'] = 'num2'
        out.append(f'{L}5')
    return d, s, f, out


